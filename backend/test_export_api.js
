// Test script for export and batch operation APIs
// Run this after starting the backend server

const API_BASE = 'http://localhost:5000/api';

// Simple test without authentication (for basic connectivity)
async function testAPI() {
    console.log('Testing API endpoints...');
    
    try {
        // Test export preview endpoint (should return empty or require auth)
        console.log('\n1. Testing export preview endpoint:');
        const previewResponse = await fetch(`${API_BASE}/admin/submissions/export/preview?limit=5`);
        console.log(`Status: ${previewResponse.status}`);
        const previewData = await previewResponse.text();
        console.log(`Response: ${previewData.substring(0, 200)}...`);
        
        // Test export endpoint
        console.log('\n2. Testing export endpoint:');
        const exportResponse = await fetch(`${API_BASE}/admin/submissions/export?format=json&limit=10`);
        console.log(`Status: ${exportResponse.status}`);
        const exportData = await exportResponse.text();
        console.log(`Response: ${exportData.substring(0, 200)}...`);
        
    } catch (error) {
        console.error('Error:', error.message);
    }
}

// Run the test
testAPI();

